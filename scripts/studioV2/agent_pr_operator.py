def run_command(command: list[str]) -> dict[str, Any]:
    completed = subprocess.run(
        command,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    return {
        "command": command,
        "returncode": completed.returncode,
        "stdout": completed.stdout,
        "stderr": completed.stderr,
    }


def python_executable() -> str:
    executable = sys.executable.strip() if isinstance(sys.executable, str) else ""
    return executable or "python"


def normalize_path(path: str) -> str:
    normalized = path.strip().replace("\\", "/")
    while normalized.startswith("./"):
        normalized = normalized[2:]
    return normalized


def load_json(path: Path) -> tuple[Any | None, str | None]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None, f"MISSING_JSON_FILE: {normalize_path(str(path))}"
    except json.JSONDecodeError as exc:
        return None, f"INVALID_JSON: {normalize_path(str(path))}: {exc}"
    except OSError as exc:
        return None, f"JSON_READ_FAILED: {normalize_path(str(path))}: {exc}"
    return payload, None


def now_iso() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def current_branch() -> tuple[str, str | None]:
    result = run_command(["git", "branch", "--show-current"])
    if result["returncode"] != 0:
        message = str(result["stderr"]).strip() or "unknown error"
        return "", f"GIT_BRANCH_QUERY_FAILED: {message}"
    return str(result["stdout"]).strip(), None


def git_status_porcelain() -> tuple[list[str], str | None]:
    result = run_command(["git", "status", "--porcelain"])
    if result["returncode"] != 0:
        message = str(result["stderr"]).strip() or "unknown error"
        return [], f"GIT_STATUS_FAILED: {message}"
    return [line.rstrip("\n") for line in str(result["stdout"]).splitlines() if line.strip()], None


def staged_files() -> tuple[list[str], str | None]:
    result = run_command(["git", "diff", "--cached", "--name-only"])
    if result["returncode"] != 0:
        message = str(result["stderr"]).strip() or "unknown error"
        return [], f"GIT_STAGED_DIFF_FAILED: {message}"
    files = [normalize_path(line) for line in str(result["stdout"]).splitlines() if line.strip()]
    return sorted(set(files)), None


def matches_pattern(path: str, pattern: str) -> bool:
    candidate = normalize_path(path)
    rule = normalize_path(pattern)
    if not rule:
        return False
    if fnmatch.fnmatchcase(candidate, rule):
        return True
    if rule.endswith("/"):
        return candidate.startswith(rule)
    return candidate == rule


def path_hits_any(path: str, patterns: list[str]) -> bool:
    return any(matches_pattern(path, pattern) for pattern in patterns)


def parse_task_packet(packet: Any) -> tuple[dict[str, Any], list[str]]:
    errors: list[str] = []
    if not isinstance(packet, dict):
        return {}, ["TASK_PACKET_NOT_OBJECT"]

    required = ["task_id", "agent_id", "allowed_files", "forbidden_files", "required_checks", "authorization"]
    for key in required:
        if key not in packet:
            errors.append(f"TASK_PACKET_MISSING_FIELD: {key}")

    allowed_files = packet.get("allowed_files")
    forbidden_files = packet.get("forbidden_files")
    required_checks = packet.get("required_checks")
    if not isinstance(allowed_files, list) or not allowed_files or not all(isinstance(x, str) and x.strip() for x in allowed_files):
        errors.append("TASK_PACKET_INVALID_ALLOWED_FILES")
    if not isinstance(forbidden_files, list) or not forbidden_files or not all(isinstance(x, str) and x.strip() for x in forbidden_files):
        errors.append("TASK_PACKET_INVALID_FORBIDDEN_FILES")
    if not isinstance(required_checks, list) or not required_checks or not all(isinstance(x, str) and x.strip() for x in required_checks):
        errors.append("TASK_PACKET_INVALID_REQUIRED_CHECKS")
    return packet, errors


def is_explicit_true(value: Any) -> bool:
    return isinstance(value, bool) and value is True


def read_authorization_flags(packet: dict[str, Any]) -> dict[str, bool]:
    authorization = packet.get("authorization")
    authz_payload = authorization if isinstance(authorization, dict) else {}
    return {
        "authorization_present": isinstance(authorization, dict),
        "human_authorized": is_explicit_true(authz_payload.get("human_authorized", False)),
        "allow_commit": is_explicit_true(authz_payload.get("allow_commit", packet.get("authorize_commit", False))),
        "allow_push": is_explicit_true(authz_payload.get("allow_push", packet.get("authorize_push", False))),
        "allow_create_pr": is_explicit_true(
            authz_payload.get("allow_create_pr", packet.get("authorize_create_pr", False))
        ),
        "allow_ready": is_explicit_true(authz_payload.get("allow_ready", packet.get("authorize_ready_pr", False))),
        "allow_merge": is_explicit_true(authz_payload.get("allow_merge", packet.get("authorize_merge_pr", False))),
    }


def collect_prepare_authorization_blockers(packet: dict[str, Any], authz_flags: dict[str, bool]) -> list[str]:
    blockers: list[str] = []
    authorization = packet.get("authorization")
    if not isinstance(authorization, dict):
        return ["missing_authorization"]

    required_fields = [
        "human_authorized",
        "allow_commit",
        "allow_push",
        "allow_create_pr",
        "allow_ready",
        "allow_merge",
    ]
    missing_fields = [field for field in required_fields if field not in authorization]
    if missing_fields:
        blockers.append("missing_authorization")

    if not authz_flags["allow_commit"]:
        blockers.append("commit_not_authorized")
    if not authz_flags["allow_push"]:
        blockers.append("push_not_authorized")
    if not authz_flags["allow_create_pr"]:
        blockers.append("create_pr_not_authorized")
    if not authz_flags["human_authorized"]:
        blockers.append("human_review_required")

    return sorted(set(blockers))


def parse_forbidden_surfaces(policy: Any) -> tuple[dict[str, list[str]], list[str]]:
    if not isinstance(policy, dict):
        return {"absolute_forbidden_paths": [], "restricted_human_review_paths": []}, ["FORBIDDEN_SURFACES_NOT_OBJECT"]
    raw_absolute = policy.get("absolute_forbidden_paths")
    raw_restricted = policy.get("restricted_human_review_paths")
    errors: list[str] = []
    if not isinstance(raw_absolute, list) or not all(isinstance(x, str) and x.strip() for x in raw_absolute):
        errors.append("FORBIDDEN_SURFACES_INVALID_ABSOLUTE_FORBIDDEN_PATHS")
    if not isinstance(raw_restricted, list) or not all(isinstance(x, str) and x.strip() for x in raw_restricted):
        errors.append("FORBIDDEN_SURFACES_INVALID_RESTRICTED_HUMAN_REVIEW_PATHS")
    if errors:
        return {"absolute_forbidden_paths": [], "restricted_human_review_paths": []}, errors
    return {
        "absolute_forbidden_paths": [normalize_path(item) for item in raw_absolute],
        "restricted_human_review_paths": [normalize_path(item) for item in raw_restricted],
    }, []


def parse_tool_matrix(policy: Any) -> list[str]:
    errors: list[str] = []
    if not isinstance(policy, dict):
        return ["TOOL_PERMISSION_MATRIX_NOT_OBJECT"]
    if policy.get("deny_by_default") is not True:
        errors.append("DENY_BY_DEFAULT_NOT_ENFORCED")
    if str(policy.get("default_effect", "")).upper() != "DENY":
        errors.append("DEFAULT_EFFECT_IS_NOT_DENY")
    return errors


def critical_freeze_by_policy(forbidden_hits: list[str], forbidden_policy: Any, freeze_policy: Any) -> bool:
    if forbidden_hits:
        return True
    if isinstance(forbidden_policy, dict) and forbidden_policy.get("critical_violation_freeze_immediate") is True:
        return False
    if isinstance(freeze_policy, dict):
        freeze_list = freeze_policy.get("freeze_immediately_on")
        if isinstance(freeze_list, list):
            return False
    return False


def validate_staged_scope(
    staged: list[str],
    allowed_files: list[str],
    task_forbidden_files: list[str],
    policy_absolute_forbidden_paths: list[str],
    policy_restricted_human_review_paths: list[str],
    packet: dict[str, Any],
    authz_flags: dict[str, bool],
) -> tuple[list[str], list[str]]:
    violations: list[str] = []
    forbidden_hits: list[str] = []
    control_plane_exception = is_explicit_true(packet.get("control_plane_exception", False))
    human_review_required = packet.get("human_review_required") is True
    exception_reason = str(packet.get("exception_reason", "")).strip()
    allow_restricted_human_review = (
        control_plane_exception
        and human_review_required
        and bool(exception_reason)
        and (authz_flags["allow_ready"] is False)
        and (authz_flags["allow_merge"] is False)
    )
    for path in staged:
        in_allowed_files = path_hits_any(path, allowed_files)
        if not in_allowed_files:
            violations.append(f"STAGED_OUTSIDE_ALLOWED_FILES: {path}")
        if path_hits_any(path, task_forbidden_files):
            forbidden_hits.append(f"TASK_FORBIDDEN_FILE_HIT: {path}")
        if path_hits_any(path, policy_absolute_forbidden_paths):
            forbidden_hits.append(f"POLICY_ABSOLUTE_FORBIDDEN_SURFACE_HIT: {path}")
        if path_hits_any(path, policy_restricted_human_review_paths):
            restricted_allowed = allow_restricted_human_review and in_allowed_files
            if not restricted_allowed:
                forbidden_hits.append(f"POLICY_RESTRICTED_HUMAN_REVIEW_SURFACE_HIT: {path}")
    return sorted(set(violations)), sorted(set(forbidden_hits))


def parse_staged_json_files(staged: list[str]) -> list[str]:
    errors: list[str] = []
    for path in staged:
        if not path.lower().endswith(".json"):
            continue
        file_path = Path(path)
        payload, err = load_json(file_path)
        if err:
            errors.append(err)
            continue
        if payload is None:
            errors.append(f"JSON_PARSE_EMPTY: {path}")
    return sorted(set(errors))


def matches_any_glob(path: str, patterns: tuple[str, ...]) -> bool:
    normalized = normalize_path(path)
    return any(fnmatch.fnmatchcase(normalized, pattern) for pattern in patterns)


def strict_schema_validation_paths(task_packet_path: Path, staged: list[str]) -> list[str]:
    paths: list[str] = [normalize_path(str(task_packet_path))]
    for path in staged:
        if not path.lower().endswith(".json"):
            continue
        if matches_any_glob(path, CONTROL_PLANE_JSON_GLOBS):
            paths.append(normalize_path(path))
    return sorted(set(paths))


def summarize_command(result: dict[str, Any]) -> dict[str, Any]:
    stdout = str(result.get("stdout", ""))
    stderr = str(result.get("stderr", ""))
    return {
        "command": result.get("command", []),
        "returncode": int(result.get("returncode", 1)),
        "stdout_tail": stdout[-4000:],
        "stderr_tail": stderr[-4000:],
    }


