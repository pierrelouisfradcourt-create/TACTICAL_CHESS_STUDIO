def default_verdicts(success: bool) -> tuple[str, str, str]:
    if success:
        return ("CONTROL_PLANE_TOOLING_ONLY", "LOCAL_OPERATOR_HYGIENE_VALIDATION_ONLY", NO_CLAIM_ALLOWED)
    return ("BLOCKED", "BLOCKED", NO_CLAIM_ALLOWED)


def build_audit_event(
    *,
    run_id: str,
    mode: str,
    branch: str,
    task_id: str,
    agent_id: str,
    checked_files: list[str],
    forbidden_hits: list[str],
    required_checks: list[str],
    checks_passed: list[str],
    checks_failed: list[str],
    freeze_required: bool,
    success: bool,
) -> dict[str, Any]:
    software_verdict, evidence_verdict, claim_verdict = default_verdicts(success)
    return {
        "run_id": run_id,
        "timestamp": now_iso(),
        "mode": mode,
        "branch": branch,
        "task_id": task_id,
        "agent_id": agent_id,
        "checked_files": checked_files,
        "forbidden_hits": forbidden_hits,
        "required_checks": required_checks,
        "checks_passed": checks_passed,
        "checks_failed": checks_failed,
        "freeze_required": freeze_required,
        "software_verdict": software_verdict,
        "evidence_verdict": evidence_verdict,
        "claim_verdict": claim_verdict,
    }


def build_reward_log(
    *,
    run_id: str,
    task_id: str,
    agent_id: str,
    checks_passed: list[str],
    checks_failed: list[str],
    strikes: int,
    freeze_required: bool,
) -> dict[str, Any]:
    positive_points = len(checks_passed) * 5
    negative_points = len(checks_failed) * 7 + strikes * 3
    autonomy_delta = "DECREASE" if freeze_required else "NONE"
    final_score = max(-100, min(100, positive_points - negative_points))
    return {
        "run_id": run_id,
        "task_id": task_id,
        "agent_id": agent_id,
        "positive_points": positive_points,
        "negative_points": negative_points,
        "strikes": strikes,
        "autonomy_delta": autonomy_delta,
        "final_score": final_score,
        "reviewed_by_human": False,
        "claim_verdict": NO_CLAIM_ALLOWED,
    }


def write_non_canonical_outputs(output_dir: Path, audit_event: dict[str, Any], reward_log: dict[str, Any]) -> list[str]:
    output_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    audit_path = output_dir / "audit_event.json"
    reward_path = output_dir / "reward_log.json"
    audit_path.write_text(json.dumps(audit_event, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    reward_path.write_text(json.dumps(reward_log, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    written.append(normalize_path(str(audit_path)))
    written.append(normalize_path(str(reward_path)))
    return written


def command_failed(result: dict[str, Any]) -> bool:
    return int(result.get("returncode", 1)) != 0


def perform_shared_loads(task_packet_path: Path) -> tuple[dict[str, Any], list[str], dict[str, Any]]:
    errors: list[str] = []
    loaded: dict[str, Any] = {}
    task_packet_payload, task_err = load_json(task_packet_path)
    if task_err:
        errors.append(task_err)
    loaded["task_packet"] = task_packet_payload

    for key, path in POLICY_PATHS.items():
        payload, err = load_json(path)
        loaded[key] = payload
        if err:
            errors.append(err)
    for key, path in SCHEMA_PATHS.items():
        payload, err = load_json(path)
        loaded[key] = payload
        if err:
            errors.append(err)

    parsed_packet, packet_errors = parse_task_packet(task_packet_payload)
    errors.extend(packet_errors)
    errors.extend(parse_tool_matrix(loaded.get("tool_permission_matrix")))
    forbidden_surface_paths, forbidden_parse_errors = parse_forbidden_surfaces(loaded.get("forbidden_surfaces"))
    errors.extend(forbidden_parse_errors)

    context = {
        "task_packet": parsed_packet,
        "policy_absolute_forbidden_paths": forbidden_surface_paths.get("absolute_forbidden_paths", []),
        "policy_restricted_human_review_paths": forbidden_surface_paths.get("restricted_human_review_paths", []),
    }
    return loaded, sorted(set(errors)), context


def deny_forbidden_cli_actions(args: argparse.Namespace, task_packet: dict[str, Any]) -> list[str]:
    violations: list[str] = []
    authz = read_authorization_flags(task_packet)
    if args.merge:
        violations.append("MERGE_REQUEST_DENIED")
    if args.ready_pr:
        violations.append("READY_PR_REQUEST_DENIED")
    if args.edit_branch_protection:
        violations.append("BRANCH_PROTECTION_EDIT_DENIED")
    # Local operator never allows these autonomous actions in this phase.
    if authz["allow_ready"]:
        violations.append("TASK_PACKET_AUTHORIZE_READY_PR_TRUE_DENIED")
    if authz["allow_merge"]:
        violations.append("TASK_PACKET_AUTHORIZE_MERGE_PR_TRUE_DENIED")
    if bool(task_packet.get("request_merge", False)):
        violations.append("TASK_PACKET_MERGE_REQUEST_DENIED")
    if bool(task_packet.get("request_ready_pr", False)):
        violations.append("TASK_PACKET_READY_PR_REQUEST_DENIED")
    if bool(task_packet.get("request_branch_protection_edit", False)):
        violations.append("TASK_PACKET_BRANCH_PROTECTION_EDIT_DENIED")
    return violations


def execute_prepare_actions(args: argparse.Namespace, branch: str) -> tuple[list[dict[str, Any]], str]:
    command_results: list[dict[str, Any]] = []

    commit_message = (args.commit_message or "").strip()
    pr_title = (args.pr_title or "").strip()
    if not commit_message:
        raise RuntimeError("MISSING_COMMIT_MESSAGE_FOR_PREPARE_DRAFT_PR")
    if not pr_title:
        raise RuntimeError("MISSING_PR_TITLE_FOR_PREPARE_DRAFT_PR")

    commit_result = run_command(["git", "commit", "-m", commit_message])
    command_results.append(summarize_command(commit_result))
    if command_failed(commit_result):
        raise RuntimeError("GIT_COMMIT_FAILED")

    push_result = run_command(["git", "push", "-u", "origin", branch])
    command_results.append(summarize_command(push_result))
    if command_failed(push_result):
        raise RuntimeError("GIT_PUSH_FAILED")

    pr_create_command = [
        "gh",
        "pr",
        "create",
        "--draft",
        "--base",
        args.base_branch,
        "--head",
        branch,
        "--title",
        pr_title,
        "--body",
        args.pr_body,
    ]
    pr_result = run_command(pr_create_command)
    command_results.append(summarize_command(pr_result))
    if command_failed(pr_result):
        raise RuntimeError("GH_PR_CREATE_FAILED")

    pr_url = str(pr_result.get("stdout", "")).strip().splitlines()[-1].strip()
    if not pr_url:
        raise RuntimeError("DRAFT_PR_URL_NOT_FOUND")
    return command_results, pr_url


def render(payload: dict[str, Any], pretty: bool) -> None:
    print(json.dumps(payload, indent=2 if pretty else None, sort_keys=True))


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    task_packet_path = Path(args.task_packet)
    output_dir = Path(args.output_dir)
    run_id = f"operator-{dt.datetime.now(dt.timezone.utc).strftime('%Y%m%dT%H%M%SZ')}-{uuid.uuid4().hex[:8]}"

    branch, branch_error = current_branch()
    status_lines, status_error = git_status_porcelain()
    loaded, load_errors, context = perform_shared_loads(task_packet_path)
    packet: dict[str, Any] = context.get("task_packet", {}) if isinstance(context.get("task_packet"), dict) else {}

    base_errors: list[str] = []
    if branch_error:
        base_errors.append(branch_error)
    if status_error:
        base_errors.append(status_error)
    base_errors.extend(load_errors)

    task_id = str(packet.get("task_id", "unknown_task"))
    agent_id = str(packet.get("agent_id", OPERATOR_AGENT_ID))
    required_checks = list(packet.get("required_checks", [])) if isinstance(packet.get("required_checks"), list) else []
    authz_flags = read_authorization_flags(packet)
    prepare_authz_blockers = collect_prepare_authorization_blockers(packet, authz_flags) if args.mode == "prepare-draft-pr" else []

    if args.mode == "inspect":
        output = {
            "run_id": run_id,
            "timestamp": now_iso(),
            "mode": "inspect",
            "branch": branch,
            "task_id": task_id,
            "agent_id": agent_id,
            "git_status_porcelain": status_lines,
            "json_parse_errors": sorted(set(base_errors)),
            "policies_loaded": sorted(POLICY_PATHS.keys()),
            "schemas_loaded": sorted(SCHEMA_PATHS.keys()),
            "software_verdict": "CONTROL_PLANE_TOOLING_ONLY" if not base_errors else "BLOCKED",
            "evidence_verdict": "SCHEMA_AND_METADATA_INSPECTION_ONLY" if not base_errors else "BLOCKED",
            "claim_verdict": NO_CLAIM_ALLOWED,
        }
        render(output, args.pretty)
        return 0 if not base_errors else 1

    staged, staged_error = staged_files()
    errors = list(base_errors)
    if staged_error:
        errors.append(staged_error)

    allowed_files = list(packet.get("allowed_files", [])) if isinstance(packet.get("allowed_files"), list) else []
    task_forbidden_files = list(packet.get("forbidden_files", [])) if isinstance(packet.get("forbidden_files"), list) else []
    policy_absolute_forbidden_paths = list(context.get("policy_absolute_forbidden_paths", []))
    policy_restricted_human_review_paths = list(context.get("policy_restricted_human_review_paths", []))

    staged_scope_violations, forbidden_hits = validate_staged_scope(
        staged=staged,
        allowed_files=allowed_files,
        task_forbidden_files=task_forbidden_files,
        policy_absolute_forbidden_paths=policy_absolute_forbidden_paths,
        policy_restricted_human_review_paths=policy_restricted_human_review_paths,
        packet=packet,
        authz_flags=authz_flags,
    )
    errors.extend(staged_scope_violations)
    errors.extend(forbidden_hits)
    json_staged_errors = parse_staged_json_files(staged)
    errors.extend(json_staged_errors)
    strict_schema_targets = strict_schema_validation_paths(task_packet_path, staged)
    strict_schema_result = run_validation(
        selected_paths=strict_schema_targets,
        include_fixtures=False,
    )
    if not strict_schema_result.get("ok", False):
        strict_errors = strict_schema_result.get("errors", [])
        if isinstance(strict_errors, list):
            for strict_error in strict_errors:
                errors.append(f"STRICT_SCHEMA_VALIDATION_FAILED: {strict_error}")
        else:
            errors.append("STRICT_SCHEMA_VALIDATION_FAILED: UNKNOWN_ERROR")

    denied_action_violations = deny_forbidden_cli_actions(args, packet)
    errors.extend(denied_action_violations)
    if prepare_authz_blockers:
        errors.extend([f"PREPARE_AUTHORIZATION_BLOCKED: {blocker}" for blocker in prepare_authz_blockers])

    check_results = run_required_local_checks()
    check_summaries = [summarize_command(result) for result in check_results]
    for result in check_summaries:
        if int(result["returncode"]) != 0:
            errors.append(f"REQUIRED_CHECK_FAILED: {' '.join(result['command'])}")

    checks_passed: list[str] = []
    checks_failed: list[str] = []
    if not staged_scope_violations:
        checks_passed.append("staged_scope_check")
    else:
        checks_failed.append("staged_scope_check")
    if not json_staged_errors:
        checks_passed.append("staged_json_parse")
    else:
        checks_failed.append("staged_json_parse")
    if strict_schema_result.get("ok", False):
        checks_passed.append("strict_schema_validation")
    else:
        checks_failed.append("strict_schema_validation")
    for summary in check_summaries:
        check_name = " ".join(summary["command"])
        if int(summary["returncode"]) == 0:
            checks_passed.append(check_name)
        else:
            checks_failed.append(check_name)

    critical_freeze = bool(forbidden_hits or denied_action_violations)
    if critical_freeze_by_policy(forbidden_hits, loaded.get("forbidden_surfaces"), loaded.get("freeze_rules")):
        critical_freeze = True

    unique_errors = sorted(set(errors))
    success = not unique_errors
    strikes = len(forbidden_hits) + len(denied_action_violations)

    audit_event = build_audit_event(
        run_id=run_id,
        mode=args.mode,
        branch=branch,
        task_id=task_id,
        agent_id=agent_id,
        checked_files=staged,
        forbidden_hits=forbidden_hits,
        required_checks=required_checks,
        checks_passed=sorted(set(checks_passed)),
        checks_failed=sorted(set(checks_failed)),
        freeze_required=critical_freeze,
        success=success,
    )
    reward_log = build_reward_log(
        run_id=run_id,
        task_id=task_id,
        agent_id=agent_id,
        checks_passed=checks_passed,
        checks_failed=checks_failed,
        strikes=strikes,
        freeze_required=critical_freeze,
    )

    written_outputs = write_non_canonical_outputs(output_dir, audit_event, reward_log)

    response: dict[str, Any] = {
        "run_id": run_id,
        "timestamp": now_iso(),
        "mode": args.mode,
        "branch": branch,
        "task_id": task_id,
        "agent_id": agent_id,
        "staged_files": staged,
        "forbidden_hits": forbidden_hits,
        "violations": unique_errors,
        "required_checks": required_checks,
        "checks_passed": sorted(set(checks_passed)),
        "checks_failed": sorted(set(checks_failed)),
        "authorization_flags": authz_flags,
        "authorization_blockers": prepare_authz_blockers,
        "freeze_required": critical_freeze,
        "audit_event_path": written_outputs[0],
        "reward_log_path": written_outputs[1],
        "check_command_results": check_summaries,
        "strict_schema_summary": strict_schema_result.get("summary", {}),
        "strict_schema_notes": strict_schema_result.get("notes", []),
        "software_verdict": audit_event["software_verdict"],
        "evidence_verdict": audit_event["evidence_verdict"],
        "claim_verdict": NO_CLAIM_ALLOWED,
    }

    if args.mode == "validate-staged":
        render(response, args.pretty)
        return 0 if success else 1

    if prepare_authz_blockers:
        response["prepare_status"] = "BLOCKED_AUTHORIZATION"
        render(response, args.pretty)
        return 1

    if not success:
        response["prepare_status"] = "BLOCKED_VALIDATE_STAGED_FAILED"
        render(response, args.pretty)
        return 1
    if not args.execute_pr_actions:
        response["prepare_status"] = "READY_DRY_RUN_ONLY"
        render(response, args.pretty)
        return 0
    try:
        prepare_commands, pr_url = execute_prepare_actions(args, branch)
    except RuntimeError as exc:
        response["prepare_status"] = "PREPARE_ACTIONS_FAILED"
        response["prepare_error"] = str(exc)
        render(response, args.pretty)
        return 1

    response["prepare_status"] = "DRAFT_PR_CREATED"
    response["draft_pr_url"] = pr_url
    response["prepare_command_results"] = prepare_commands
    render(response, args.pretty)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
